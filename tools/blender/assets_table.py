#!/usr/bin/env python3
"""Regenerates the per-asset table in ASSETS.md (between the RJ-TABLE markers) from the build
manifests in reference-images/previews/*/manifest.json. build.py runs it after every build.
    py tools/blender/assets_table.py
"""
import glob, json, os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
MD = os.path.join(ROOT, "ASSETS.md")
BEGIN, END = "<!-- RJ-TABLE:BEGIN (generated by tools/blender/assets_table.py) -->", "<!-- RJ-TABLE:END -->"
ORDER = ["kit", "props", "glint", "gear", "meshy", "chars"]


def rows():
    out = ["| Asset | Source | Status | Path | Notes |", "| --- | --- | --- | --- | --- |"]
    mans = {}
    for f in glob.glob(os.path.join(ROOT, "reference-images", "previews", "*", "manifest.json")):
        m = json.load(open(f))
        if m["lib"] != "inspect":          # inspection sheets are not assets
            mans[m["lib"]] = m
    for lib in sorted(mans, key=lambda k: (ORDER.index(k) if k in ORDER else 99, k)):
        m = mans[lib]
        if lib == "chars":
            for g in m["glbs"]:
                name = os.path.basename(g)[:-4]
                out.append(f"| `{name}` | script (stand-in) | placeholder | `{g}` | "
                           f"shared stand-in rig, clips: {', '.join(m['clips'])} |")
            continue
        if lib == "meshy":
            for g in m["glbs"]:
                name = os.path.basename(g)[:-4]
                c = m["chars"][name[5:]]
                out.append(f"| `{name}` | Meshy (pilot), imported by `tools/blender/meshy_build.py` | done (pilot, pending Kyle's review) | `{g}` | "
                           f"{c['tris']} tris, own Meshy rig, clips: {', '.join(c['clips'])} |")
            continue
        for p in m["pieces"]:
            kids = f" Children: {', '.join('`' + c + '`' for c in p['children'])}." if p["children"] else ""
            note = (p["note"] + "." if p["note"] else "") + kids
            out.append(f"| `{p['name']}` | script `tools/blender/{lib}_build.py` | done | `{m['glb']}` | "
                       f"{p['tris']} tris. {note} |")
    return out


def main():
    md = open(MD, encoding="utf8").read()
    if BEGIN not in md:
        md = md.rstrip() + "\n\n" + BEGIN + "\n" + END + "\n"
    a, b = md.index(BEGIN) + len(BEGIN), md.index(END)
    md = md[:a] + "\n" + "\n".join(rows()) + "\n" + md[b:]
    open(MD, "w", encoding="utf8").write(md)
    print("  ASSETS.md table updated")


if __name__ == "__main__":
    main()
